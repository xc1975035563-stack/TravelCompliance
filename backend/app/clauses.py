def render_clause(code: str, policy_clauses: dict | None = None, gap: int | None = None) -> str:
    text = None
    if policy_clauses:
        text = policy_clauses.get(code)
    if not text:
        text = FALLBACK_CLAUSES.get(code, code)
    if "{gap}" in text:
        text = text.format(gap=0 if gap is None else gap)
    return text
